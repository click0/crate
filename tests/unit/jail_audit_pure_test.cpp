ATF_TEST_CASE_WITHOUT_HEAD(probe_script_shape);
ATF_TEST_CASE_BODY(probe_script_shape) {
  auto s = probeScript(false, "www.freebsd.org");
  for (const char *m : {"@@id", "@@sysctl", "@@mount", "@@ifconfig", "@@routes", "@@dev",
                        "@@sockets", "@@fssockets", "@@ps", "@@resolv", "@@gw", "@@connect", "@@dns"})
    ATF_REQUIRE(s.find(m) != std::string::npos);
  ATF_REQUIRE(s.find("drill -Q A 'www.freebsd.org'") != std::string::npos);
  ATF_REQUIRE(s.find("nc -z -w 3") != std::string::npos);
  // base-system paths only, no /usr/local
  ATF_REQUIRE(s.find("/usr/local") == std::string::npos);

  auto off = probeScript(true, "www.freebsd.org");
  ATF_REQUIRE(off.find("@@connect") == std::string::npos);
  ATF_REQUIRE(off.find("@@dns") == std::string::npos);
  ATF_REQUIRE(off.find("drill") == std::string::npos);
  ATF_REQUIRE(off.find("@@gw") != std::string::npos);   // the gateway is still reported
}

ATF_TEST_CASE_WITHOUT_HEAD(split_sections);
ATF_TEST_CASE_BODY(split_sections) {
  auto s = splitSections("noise before the first marker\n"
                         "@@one\na\nb\n"
                         "@@gw 10.0.0.1\n"
                         "@@connect\nsome text\n@@rc=1\n"
                         "@@empty\n"
                         "@@dns\n1.2.3.4\n@@rc=0\n");
  ATF_REQUIRE_EQ(s.at("one"), std::string("a\nb\n"));
  ATF_REQUIRE_EQ(s.at("gw"), std::string("10.0.0.1\n"));
  ATF_REQUIRE_EQ(s.at("connect"), std::string("some text\n"));
  ATF_REQUIRE_EQ(s.at("connect.rc"), std::string("1"));
  ATF_REQUIRE_EQ(s.at("empty"), std::string(""));
  ATF_REQUIRE_EQ(s.at("dns.rc"), std::string("0"));
  ATF_REQUIRE(s.find("noise") == s.end());
  // CRLF tolerated, empty input -> no sections
  ATF_REQUIRE(splitSections("").empty());
  ATF_REQUIRE_EQ(splitSections("@@x\r\nv\r\n").at("x"), std::string("v\n"));
}

