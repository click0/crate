  ATF_REQUIRE(sc.find("security.jail.param.allow.mlock") == sc.end());
  ATF_REQUIRE_EQ(sc.at("sysctl"), std::string("unknown oid 'bogus'"));   // harmless

  auto ps = parsePs("root       1 sh\nalice   2000 firefox\nbad line\nwww  x nginx\n");
  ATF_REQUIRE_EQ(ps.size(), 2u);
  ATF_REQUIRE_EQ(ps[1].user, std::string("alice"));
  ATF_REQUIRE_EQ(ps[1].pid, 2000);
  ATF_REQUIRE_EQ(ps[1].command, std::string("firefox"));

  auto ns = parseResolvConf("# comment\nsearch example.org\nnameserver 10.0.0.1\nnameserver 2001:db8::1\n");
  ATF_REQUIRE_EQ(ns.size(), 2u);
  ATF_REQUIRE_EQ(ns[1], std::string("2001:db8::1"));
