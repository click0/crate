  ATF_REQUIRE_EQ(so[0].local, std::string("*:80"));
  ATF_REQUIRE_EQ(so[0].foreign, std::string("*:*"));
  ATF_REQUIRE_EQ(so[2].proto, std::string("dgram"));
  ATF_REQUIRE(so[2].foreign.empty());

  auto sc = parseSysctl("kern.securelevel=-1\n"
                        "kern.hostname: with-colon-form\n"
                        "security.jail.jailed=1\n"
                        "security.jail.param.path=1024\n"
                        "security.jail.param.allow.mlock=0\n"
                        "sysctl: unknown oid 'bogus'\n");
