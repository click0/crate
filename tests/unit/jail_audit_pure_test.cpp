const Check *find(const Report &r, const std::string &category, const std::string &name) {
  for (const auto &c : r.checks)
    if (c.category == category && c.name == name) return &c;
  return nullptr;
}

unsigned countCategory(const Report &r, const std::string &category) {
  unsigned n = 0;
  for (const auto &c : r.checks) if (c.category == category) n++;
  return n;
}

