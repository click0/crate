ATF_TEST_CASE_WITHOUT_HEAD(report_desktop_jail);
ATF_TEST_CASE_BODY(report_desktop_jail) {
  HostContext ctx;
  ctx.jailName = "firefox";
  ctx.jid = 7;
  ctx.hostHostid = "1234567890";          // same as inside -> WARN
  ctx.hostHostname = "workstation.lan";   // differs
  ctx.dnsName = "www.freebsd.org";
  auto r = buildReport(kDesktopProbe, ctx);

  ATF_REQUIRE_EQ(countCategory(r, "probe"), 0u);   // every section present

  // jail
  ATF_REQUIRE(find(r, "jail", "jailed")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "jail", "hostname")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "jail", "hostid")->severity == Severity::Warn);
  ATF_REQUIRE(find(r, "jail", "raw-sockets")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "jail", "vnet")->detail.find("own network stack") != std::string::npos);
  ATF_REQUIRE(find(r, "jail", "enforce-statfs")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "jail", "devfs-ruleset")->detail == "ruleset 7");

  // mounts: the whole home rw -> WARN, Downloads rw -> PASS, X11 ro -> PASS, procfs -> WARN
  ATF_REQUIRE(find(r, "mounts", "/home/alice")->severity == Severity::Warn);
  ATF_REQUIRE(find(r, "mounts", "/home/alice/Downloads")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "mounts", "/tmp/.X11-unix")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "mounts", "/usr/share")->detail.find("ro from host /usr/share") != std::string::npos);
  ATF_REQUIRE(find(r, "mounts", "/proc")->severity == Severity::Warn);
  ATF_REQUIRE(find(r, "mounts", "/")->detail.find("zfs rw dataset zroot/crate/jails/firefox") != std::string::npos);

  // devfs: gpu + sound classes, no raw/disks/input
  ATF_REQUIRE(find(r, "devfs", "gpu") != nullptr);
  ATF_REQUIRE(find(r, "devfs", "sound")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "devfs", "raw") == nullptr);
  ATF_REQUIRE(find(r, "devfs", "disks") == nullptr);
  ATF_REQUIRE(find(r, "devfs", "input") == nullptr);
  ATF_REQUIRE(find(r, "devfs", "entries")->detail.find("14 in /dev") != std::string::npos);

  // interfaces
  ATF_REQUIRE(find(r, "interfaces", "epair3b")->detail.find("inet 10.0.3.2") != std::string::npos);
  ATF_REQUIRE(find(r, "interfaces", "default-route")->detail == "via 10.0.3.1");

  // sockets: host X11 and system D-Bus -> WARN, syslog sockets collapsed into one PASS
  ATF_REQUIRE(find(r, "sockets", "/tmp/.X11-unix/X0")->severity == Severity::Warn);
  ATF_REQUIRE(find(r, "sockets", "/var/run/dbus/system_bus_socket")->severity == Severity::Warn);
  ATF_REQUIRE(find(r, "sockets", "/var/run/dbus/system_bus_socket")->detail.find("nullfs from host /var/run/dbus") != std::string::npos);
  ATF_REQUIRE(find(r, "sockets", "jail-local")->detail.find("2 unix socket(s)") != std::string::npos);
  ATF_REQUIRE(find(r, "sockets", "listen")->detail == "no inet listeners");

  // processes
  const Check *p = find(r, "processes", "running");
  ATF_REQUIRE(p != nullptr);
  ATF_REQUIRE(p->detail.find("4 process(es)") != std::string::npos);
  ATF_REQUIRE(p->detail.find("alice: 2") != std::string::npos);
  ATF_REQUIRE(p->detail.find("root: 2") != std::string::npos);
  ATF_REQUIRE(find(r, "processes", "probe-ran-as")->detail.find("uid=0(root)") != std::string::npos);

  // connectivity: refused = reachable, DNS answered
  ATF_REQUIRE(find(r, "connectivity", "resolver")->detail == "nameserver 10.0.3.1");
  ATF_REQUIRE(find(r, "connectivity", "gateway")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "connectivity", "gateway")->detail.find("reachable (tcp/22 refused)") != std::string::npos);
  ATF_REQUIRE(find(r, "connectivity", "dns")->severity == Severity::Pass);
  ATF_REQUIRE(find(r, "connectivity", "dns")->detail == "www.freebsd.org -> 96.47.72.84");

  // exit code: WARNs, no FAIL -> 1; JSON renders with the summary
  ATF_REQUIRE_EQ(DoctorPure::exitCodeFor(r), 1);
  auto json = DoctorPure::renderJson(r);
  ATF_REQUIRE(json.find("\"category\":\"mounts\"") != std::string::npos);
  ATF_REQUIRE(json.find("\"fail\":0") != std::string::npos);
  auto text = DoctorPure::renderText(r, true);
  // category order: jail before mounts before connectivity
  ATF_REQUIRE(text.find("jail:") < text.find("mounts:"));
  ATF_REQUIRE(text.find("mounts:") < text.find("connectivity:"));
}

